#!/usr/bin/env python3
"""
EakUI icon generator.

Reads tools/icons/icons.json (the single source of truth) and generates:

  assets/icons/png/<name>.png      white 96x96 PNGs loaded by Roblox (tinted at runtime)
  assets/icons/svg/<name>.svg      white SVG sources
  assets/icons/preview/<name>.svg  grey SVGs that are visible on GitHub (used by ICONS.md)
  src/Core/IconList.lua            generated Lua registry (names, categories, aliases)
  ICONS.md                         icon reference with previews

Rendering uses `rsvg-convert` (librsvg) or the `cairosvg` Python package.

Usage:
    python tools/build_icons.py
    python tools/build.py          # then rebuild dist/EakUI.lua
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tools" / "icons" / "icons.json"
ASSETS = ROOT / "assets" / "icons"
PNG_DIR = ASSETS / "png"
SVG_DIR = ASSETS / "svg"
PREVIEW_DIR = ASSETS / "preview"
LUA_OUT = ROOT / "src" / "Core" / "IconList.lua"
DOC_OUT = ROOT / "ICONS.md"

PNG_SIZE = 96
RUNTIME_COLOR = "#FFFFFF"  # white so ImageColor3 can tint it
PREVIEW_COLOR = "#8B8BA0"  # readable on GitHub light and dark themes
DOC_COLUMNS = 6


def svg_markup(paths: list[str], color: str, size: int, stroke: float) -> str:
    body = "".join(f'<path d="{d}"/>' for d in paths)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 24 24" '
        f'fill="none" stroke="{color}" stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">'
        f"{body}</svg>\n"
    )


def find_renderer():
    if shutil.which("rsvg-convert"):
        def render(svg_path: Path, png_path: Path) -> None:
            subprocess.run(
                ["rsvg-convert", "-w", str(PNG_SIZE), "-h", str(PNG_SIZE), "-o", str(png_path), str(svg_path)],
                check=True,
            )
        return render
    try:
        import cairosvg  # type: ignore

        def render(svg_path: Path, png_path: Path) -> None:
            cairosvg.svg2png(url=str(svg_path), write_to=str(png_path), output_width=PNG_SIZE, output_height=PNG_SIZE)
        return render
    except ImportError:
        sys.exit("No SVG renderer found. Install librsvg (rsvg-convert) or `pip install cairosvg`.")


def lua_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_lua(icons: list[dict], aliases: dict[str, str]) -> None:
    categories: "OrderedDict[str, list[str]]" = OrderedDict()
    for icon in icons:
        categories.setdefault(icon["category"], []).append(icon["name"])

    lines = [
        "--[[",
        "\tCore/IconList",
        "\tGENERATED by tools/build_icons.py from tools/icons/icons.json - do not edit by hand.",
        "]]",
        "",
        "return {",
        "\tCategories = {",
    ]
    for category, names in categories.items():
        joined = ", ".join(lua_string(n) for n in names)
        lines.append(f"\t\t{{ Name = {lua_string(category)}, Icons = {{ {joined} }} }},")
    lines.append("\t},")
    lines.append("\tAliases = {")
    for alias, target in sorted(aliases.items()):
        lines.append(f"\t\t[{lua_string(alias)}] = {lua_string(target)},")
    lines.append("\t},")
    lines.append("}")
    LUA_OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def write_doc(icons: list[dict], aliases: dict[str, str]) -> None:
    categories: "OrderedDict[str, list[dict]]" = OrderedDict()
    for icon in icons:
        categories.setdefault(icon["category"], []).append(icon)

    out = [
        "# EakUI Icons",
        "",
        f"EakUI ships **{len(icons)} built-in icons** that you can use by name anywhere an image is accepted.",
        "",
        "```lua",
        'Window:Tab({ Title = "Settings", Icon = "settings" })',
        'Tab:Button({ Title = "Teleport", Icon = "map-pin" })',
        'Tab:Toggle({ Title = "God Mode", Icon = "shield" })',
        'UI:Notify({ Title = "Saved", Icon = "check-circle" })',
        "```",
        "",
        "## How it works",
        "",
        "- Icons are white line icons on a 24px grid (Lucide style). Element and tab icons are tinted by the theme automatically.",
        "- The first time an icon is used, it is downloaded from this repository into `workspace/EakUI/assets/` and reused after that.",
        "- This needs an executor with `writefile` and `getcustomasset`, which is the same requirement as URL images.",
        "- Asset IDs (`rbxassetid://...`), URLs and workspace files still work exactly as before.",
        "- `UI:GetIcons()` returns every name grouped by category.",
        "- `UI:SetIconBaseUrl(url)` loads icons from your own host instead of this repository.",
        "- `UI:Preload({ \"settings\", \"sword\" })` downloads icons ahead of time so they appear instantly.",
        "",
        "## Names are case-insensitive",
        "",
        '`"Settings"`, `"settings"` and `"SETTINGS"` all work. Spaces and underscores become dashes, so `"map pin"` and `"map_pin"` both resolve to `"map-pin"`.',
        "",
        "## Icons",
        "",
    ]

    for category, items in categories.items():
        out.append(f"### {category} ({len(items)})")
        out.append("")
        out.append("| " + " | ".join([" "] * DOC_COLUMNS) + " |")
        out.append("|" + "---|" * DOC_COLUMNS)
        for start in range(0, len(items), DOC_COLUMNS):
            row = items[start : start + DOC_COLUMNS]
            cells = [
                f'<img src="assets/icons/preview/{icon["name"]}.svg" width="28" height="28" alt="{icon["name"]}"><br>`{icon["name"]}`'
                for icon in row
            ]
            cells += [" "] * (DOC_COLUMNS - len(cells))
            out.append("| " + " | ".join(cells) + " |")
        out.append("")

    out += [
        "## Aliases",
        "",
        "Common alternative names map to the icons above:",
        "",
        "| Alias | Icon |",
        "|---|---|",
    ]
    for alias, target in sorted(aliases.items()):
        out.append(f"| `{alias}` | `{target}` |")
    out += [
        "",
        "## Adding an icon",
        "",
        "1. Add an entry to `tools/icons/icons.json` with a `name`, a `category` and `paths` (SVG path data on a 24x24 grid, stroke only).",
        "2. Run `python tools/build_icons.py`. This regenerates the PNGs, SVGs, `src/Core/IconList.lua` and this file.",
        "3. Run `python tools/build.py`, then publish with `tools/publish.bat`.",
        "",
        "## License",
        "",
        "Some icons use path data from [Lucide](https://lucide.dev) (ISC License); the others were drawn for EakUI in the same style. "
        "See [assets/icons/LICENSE-LUCIDE.txt](assets/icons/LICENSE-LUCIDE.txt).",
        "",
    ]
    DOC_OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")


def main() -> None:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    icons: list[dict] = data["icons"]
    aliases: dict[str, str] = data.get("aliases", {})
    stroke = data.get("strokeWidth", 2)

    names = [icon["name"] for icon in icons]
    duplicates = {n for n in names if names.count(n) > 1}
    if duplicates:
        sys.exit(f"Duplicate icon names: {', '.join(sorted(duplicates))}")
    broken = {a: t for a, t in aliases.items() if t not in names}
    if broken:
        sys.exit(f"Aliases pointing to unknown icons: {broken}")
    clashing = set(aliases) & set(names)
    if clashing:
        sys.exit(f"Aliases that shadow real icon names: {', '.join(sorted(clashing))}")

    render = find_renderer()
    for folder in (PNG_DIR, SVG_DIR, PREVIEW_DIR):
        if folder.exists():
            shutil.rmtree(folder)
        folder.mkdir(parents=True)

    for icon in icons:
        svg_path = SVG_DIR / f"{icon['name']}.svg"
        svg_path.write_text(svg_markup(icon["paths"], RUNTIME_COLOR, 24, stroke), encoding="utf-8")
        (PREVIEW_DIR / f"{icon['name']}.svg").write_text(
            svg_markup(icon["paths"], PREVIEW_COLOR, 24, stroke), encoding="utf-8"
        )
        render(svg_path, PNG_DIR / f"{icon['name']}.png")

    write_lua(icons, aliases)
    write_doc(icons, aliases)
    print(f"Generated {len(icons)} icons ({len(aliases)} aliases): PNG + SVG + preview, IconList.lua, ICONS.md")


if __name__ == "__main__":
    main()
